// Bir İngilizce cümledeki sözlükte bulunan kelimeleri "kelime = anlam" listesi olarak verir
window.kelimeAnlamlari = function (cumle, enFazla = 6) {
  const S = window.SOZLUK, t = cumle.toLowerCase().replace(/[^a-z' ]/g, " ");
  const bulunan = [], kullanilan = new Set();
  for (const ifade of Object.keys(S).filter((k) => k.includes(" "))) {
    if (new RegExp("\\b" + ifade + "\\b").test(t)) { bulunan.push([ifade, S[ifade]]); ifade.split(" ").forEach((w) => kullanilan.add(w)); }
  }
  const kok = (w) => {
    if (S[w]) return w;
    const adaylar = [w.replace(/ies$/, "y"), w.replace(/es$/, ""), w.replace(/s$/, ""), w.replace(/ing$/, ""), w.replace(/ing$/, "e"), w.replace(/ed$/, ""), w.replace(/'s$/, "")];
    return adaylar.find((a) => S[a]);
  };
  for (const w of t.split(/\s+/)) {
    if (!w || kullanilan.has(w)) continue;
    const k = kok(w);
    if (k && !bulunan.some((b) => b[0] === k)) bulunan.push([k, S[k]]);
  }
  return bulunan.slice(0, enFazla);
};
